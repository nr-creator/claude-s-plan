import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const url = 'http://localhost:8123/';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const errors = [];
const ctx = await browser.newContext({ viewport: { width: 1400, height: 950 }, locale: 'uk-UA', timezoneId: 'Europe/Zurich' });
const p = await ctx.newPage();
p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errors.push(`${m.type()}: ${m.text()}`); });
p.on('pageerror', e => errors.push(`pageerror: ${e.message}\n${e.stack}`));
await p.goto(url + '#/notes'); await p.waitForTimeout(600);
await p.click('[data-act="new-note"]'); await p.waitForTimeout(300);
const k = p.keyboard;
await k.type('Лекція 5: Похідні');
await k.press('Enter'); await p.waitForTimeout(100);
await k.type('# Означення'); await k.press('Enter');
await k.type('Похідна функції — це **границя** відношення приросту, тобто $f\'(x)$ показує *швидкість* зміни. ');
await k.press('Enter');
await k.type('$$'); await p.waitForTimeout(50);
await k.type('f\'(x) = \\lim_{\\Delta x \\to 0} \\frac{f(x+\\Delta x) - f(x)}{\\Delta x}');
await k.press('Enter');
await k.type('## Правила'); await k.press('Enter');
await k.type('- сума: $(u+v)\' = u\' + v\'$'); await k.press('Enter');
await k.type('добуток'); await k.press('Tab'); await k.type(' $(uv)\' = u\'v + uv\'$'); await k.press('Enter');
await k.press('Enter'); await k.press('Enter');
await k.type('[] розв\'язати задачі 1–10'); await k.press('Enter');
await k.type('повторити таблицю'); await k.press('Enter'); await k.press('Enter');
await k.type('/табл'); await p.waitForTimeout(150);
await p.screenshot({ path: 'tests/shot-ed-slash.png' });
await k.press('Enter'); await p.waitForTimeout(100);
await k.type('f(x)'); await k.press('Tab'); await k.type("f'(x)"); await k.press('Tab'); await k.type('x^n'); await k.press('Tab'); await k.type('$nx^{n-1}$ ');
await k.press('ArrowDown'); await p.waitForTimeout(80);
await k.type('! '); await p.waitForTimeout(100);
await k.type('Не плутати з диференціалом');
await k.press('Enter');
await k.type('```'); await k.type('def d(f, x, h=1e-6):'); await k.press('Enter'); await k.type('    return (f(x+h)-f(x))/h');
await k.press('Control+Enter');
await k.type('+ Доведення'); await k.press('Enter'); await k.type('Схована частина');
await p.waitForTimeout(800);
await p.screenshot({ path: 'tests/shot-ed-1.png' });
const getMd = () => p.evaluate(() => window.__plan.store.entries().find(e => e.title && e.title.startsWith('Лекція 5')).body);
console.log('---- MD ----\n' + await getMd() + '\n------------');
await k.press('Control+z'); await p.waitForTimeout(600);
console.log('after undo tail:', JSON.stringify((await getMd()).slice(-50)));
await k.press('Control+Shift+z'); await p.waitForTimeout(600);
console.log('after redo tail:', JSON.stringify((await getMd()).slice(-50)));
// Esc: вибір блоку → ще Esc → закриття
await k.press('Escape'); await p.waitForTimeout(100);
console.log('block selected:', await p.evaluate(() => document.querySelectorAll('.blk.sel').length));
await k.press('Escape'); await p.waitForTimeout(100); await k.press('Escape'); await p.waitForTimeout(300);
console.log('panel open after esc:', await p.evaluate(() => document.body.classList.contains('panel-open')));
await p.click('.note-card'); await p.waitForTimeout(500);
await p.click('[data-pn="full"]'); await p.waitForTimeout(300);
await p.screenshot({ path: 'tests/shot-ed-2-full.png' });
// Видалення порожнього нового запису
await p.click('[data-pn="full"]'); await k.press('Escape'); await p.waitForTimeout(300);
await p.click('[data-act="new-note"]'); await p.waitForTimeout(300); await k.press('Escape'); await p.waitForTimeout(400);
console.log('notes count (should be 1):', await p.evaluate(() => window.__plan.store.entries().length));
console.log(errors.join('\n') || 'no console errors');
await browser.close();
