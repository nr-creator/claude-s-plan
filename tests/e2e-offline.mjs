import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const errors = [];
const ctx = await browser.newContext({ viewport: { width: 1200, height: 850 }, locale: 'uk-UA', timezoneId: 'Europe/Zurich' });
const p = await ctx.newPage();
p.on('pageerror', e => errors.push(e.message));
await p.goto('http://localhost:8123/'); await p.waitForTimeout(500);
await p.evaluate(async () => { await window.__plan.store.createEntry({ title: 'Офлайн-нотатка', body: 'текст' }); });
await p.evaluate(() => navigator.serviceWorker.ready);
await p.reload(); await p.waitForTimeout(800);
const cached = await p.evaluate(async () => { const k = await caches.keys(); const c = await caches.open(k[0]); return (await c.keys()).length; });
console.log('cached files:', cached);
await ctx.setOffline(true);
await p.reload(); await p.waitForTimeout(800);
const titles = await p.evaluate(() => window.__plan.store.entries().map(e => e.title));
assert.deepEqual(titles, ['Офлайн-нотатка']);
await p.goto('http://localhost:8123/#/notes'); await p.waitForTimeout(500);
await p.fill('.qa-in', 'додано без інтернету'); await p.press('.qa-in', 'Enter'); await p.waitForTimeout(300);
assert.equal(await p.evaluate(() => window.__plan.store.entries().length), 2);
await p.screenshot({ path: 'tests/shot-offline.png' });
console.log('offline ok; sync label:', await p.evaluate(() => document.querySelector('.rail .sync-btn').textContent));
await ctx.setOffline(false);
// Маніфест
const man = await (await fetch('http://localhost:8123/manifest.webmanifest')).json();
assert.equal(man.display, 'standalone'); assert.ok(man.icons.some(i => i.sizes === '512x512'));
// Перенесення налаштувань QR-кодом
await p.evaluate(() => window.__plan.store.saveSpaces([{ id: 'local', name: '', kind: 'personal', color: 'teal', login: 'artem', remote: { owner: 'artem', repo: 'plan-data', token: 'github_pat_SECRET123', branch: 'main' } }, { id: 'shared', name: 'Навчання', kind: 'shared', color: 'violet', remote: { owner: 'study', repo: 'shared', token: 'github_pat_SECRET456', branch: 'main' } }]));
await p.goto('http://localhost:8123/#/settings'); await p.waitForTimeout(300);
await p.click('[data-go="transfer"]'); await p.waitForTimeout(200);
await p.fill('.tr-pin', '4821'); await p.click('[data-make]'); await p.waitForTimeout(400);
await p.screenshot({ path: 'tests/shot-qr.png' });
const svg = await p.evaluate(() => document.querySelector('.qr-box svg').outerHTML);
(await import('node:fs')).writeFileSync('tests/qr-ui.svg', svg);
const link = await p.evaluate(() => window.__plan.lastTransfer || null);
// Беремо код зі стану модуля: генеруємо ще раз тим самим шляхом
const code = await p.evaluate(async () => (await import('./js/transfer.js')).pack('4821'));
assert.ok(!code.includes('SECRET'));
const ctx2 = await browser.newContext({ viewport: { width: 390, height: 800 }, isMobile: true, hasTouch: true });
const q = await ctx2.newPage(); q.on('pageerror', e => errors.push('phone: ' + e.message));
await q.route('https://api.github.com/**', r => r.fulfill({ status: 401, body: '{}' }));
await q.goto('http://localhost:8123/#setup=' + code); await q.waitForTimeout(800);
await q.fill('.tr-pin', '0000'); await q.press('.tr-pin', 'Enter'); await q.waitForTimeout(400);
assert.ok(await q.isVisible('.form-msg.err'));
await q.fill('.tr-pin', '4821'); await q.press('.tr-pin', 'Enter'); await q.waitForTimeout(500);
await q.screenshot({ path: 'tests/shot-qr-import.png' });
await q.click('.modal [data-y]'); await q.waitForTimeout(400);
const sp = await q.evaluate(() => window.__plan.store.spaces.map(s => [s.id, s.kind, s.remote && s.remote.repo, s.remote && s.remote.token.slice(-3)]));
console.log('phone spaces:', JSON.stringify(sp));
assert.equal(sp.length, 2); assert.equal(sp[0][0], 'local'); assert.equal(sp[0][2], 'plan-data'); assert.equal(sp[1][3], '456');
assert.ok(!(await q.evaluate(() => location.hash)).includes('setup'));
console.log(errors.join('\n') || 'no page errors');
await browser.close();
